require_pattern "$macos_input" "setPlaceholderString: placeholder" "macOS placeholder"
require_pattern "$macos_input" "makeFirstResponder: self\\.field" "macOS focus command"
require_pattern "$macos_input" "makeFirstResponder: nil" "macOS blur command"
require_pattern "$macos_input" "selectText: nil" "macOS select all command"
require_pattern "$macos_input" "sel!\\(copy:\\)" "macOS copy command"
require_pattern "$macos_input" "sel!\\(cut:\\)" "macOS cut command"
require_pattern "$macos_input" "sel!\\(paste:\\)" "macOS paste command"
require_pattern "$macos_input" "performSelector: selector withObject: nil" "macOS edit command dispatch"
require_pattern "$macos_input" "setDelegate: nil" "macOS delegate cleanup"
require_pattern "$macos_input" "Retain count: alloc/init -> 1" "macOS retain-count cleanup comment"
