require_pattern "$macos_input" "msg_send!\\[self\\.host_view, release\\]" "macOS host view release"
require_pattern "$macos_input" "msg_send!\\[self\\.delegate, release\\]" "macOS delegate release"
require_pattern "$macos_input" "NATIVE_TEXT_INPUT_LIVE_COUNT\\.fetch_add" "macOS leak counter increment"
