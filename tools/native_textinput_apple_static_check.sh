require_pattern "$ios_input" "if is_programmatic != NO" "iOS programmatic guard"
require_pattern "$ios_input" "NativeTextInputChanged::new\\(text_input_id\\(this\\), text\\)" "iOS changed action"
require_pattern "$ios_input" "NativeTextInputFocusChanged::new\\(" "iOS focus action"
require_pattern "$ios_input" "NativeTextInputSelectionChanged::new\\(" "iOS selection action"
