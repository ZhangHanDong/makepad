require_pattern "$macos_input" "decl\\.add_ivar::<BOOL>\\(\"is_programmatic_update\"\\)" "macOS programmatic ivar"
require_pattern "$macos_input" "if is_programmatic != NO" "macOS programmatic guard"
require_pattern "$macos_input" "NativeTextInputChanged::new\\(text_input_id\\(this\\), text\\)" "macOS changed action"
